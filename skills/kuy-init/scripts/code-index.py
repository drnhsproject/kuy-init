#!/usr/bin/env python3
"""Build a compact, grep-friendly symbol index of the project in .agents/code-analysis/.

One line per symbol: `name | kind | path:line | signature | first doc line`.
Python is parsed with `ast`; other languages with best-effort line patterns (INDEX.md says so).
Standard library only. Incremental: unchanged files are not re-read (hash cache).

Usage:
  python3 .agents/scripts/code-index.py                  build or refresh the index
  python3 .agents/scripts/code-index.py --force          also build when graphify is present
  python3 .agents/scripts/code-index.py --scope=src/api  only index that path (other files kept)
  python3 .agents/scripts/code-index.py --graphify       only report whether graphify is usable
"""
from __future__ import annotations

import ast
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

AGENTS_DIR = Path(__file__).resolve().parents[1]
ROOT = AGENTS_DIR.parent
OUT = AGENTS_DIR / "code-analysis"
CACHE = OUT / ".cache.json"
GENERATED = "<!-- generated by .agents/scripts/code-index.py: do not edit by hand -->"
MAX_BYTES = 512_000
MAX_LINES_PER_FILE = 300
SKIP_DIRS = {".git", "node_modules", "dist", "build", "out", "vendor", "target", "__pycache__", ".venv",
             "venv", ".agents", "graphify-out", "coverage", ".next", ".nuxt", ".cache", ".idea", ".vscode",
             "storage", "bin", "obj"}
WIDE_ROOTS = {"src", "app", "lib", "packages", "apps", "internal", "cmd", "pkg", "services", "modules"}

LANG = {".py": "python", ".ts": "ts", ".tsx": "ts", ".js": "ts", ".jsx": "ts", ".mjs": "ts", ".cjs": "ts",
        ".vue": "ts", ".svelte": "ts", ".php": "php", ".go": "go", ".java": "java", ".kt": "kotlin",
        ".rs": "rust", ".rb": "ruby", ".cs": "csharp", ".swift": "swift"}
BEST_EFFORT = sorted({v for v in LANG.values() if v != "python"})

MOD = r"(?:(?:public|private|protected|internal|static|final|abstract|override|async|export|default|open|sealed|readonly|pub|unsafe|suspend|data|declare)\s+)*"
PATTERNS: dict[str, list[tuple[str, str]]] = {
    "ts": [
        ("class", rf"^\s*{MOD}class\s+(\w+)"),
        ("iface", rf"^\s*{MOD}interface\s+(\w+)"),
        ("type", rf"^\s*{MOD}type\s+(\w+)\s*(?:<[^=]*>)?\s*="),
        ("enum", rf"^\s*{MOD}(?:const\s+)?enum\s+(\w+)"),
        ("fn", rf"^\s*{MOD}function\*?\s+(\w+)"),
        ("fn", rf"^\s*{MOD}(?:const|let|var)\s+(\w+)\s*(?::[^=]+)?=\s*(?:async\s*)?(?:\([^)]*\)|\w+)\s*(?::[^=]+)?=>"),
        ("fn", rf"^\s*{MOD}(?:const|let|var)\s+(\w+)\s*=\s*(?:async\s+)?function\b"),
        ("member", rf"^\s+{MOD}(?:get\s+|set\s+)?\*?(\w+)\s*(?:<[^>(]*>)?\s*\([^)]*\)?\s*(?::\s*[^{{=]+)?\{{.*$"),
        ("const", r"^(?:export\s+)?(?:const|let|var)\s+([A-Z][A-Z0-9_]{2,})\b"),
        ("const", r"^export\s+(?:const|let|var)\s+(\w+)"),
    ],
    "php": [
        ("class", rf"^\s*{MOD}(?:class|trait|interface|enum)\s+(\w+)"),
        ("fn", rf"^\s*{MOD}function\s+&?(\w+)\s*\("),
        ("const", rf"^\s*{MOD}const\s+(\w+)\s*="),
    ],
    "go": [
        ("type", r"^type\s+(\w+)\s+(?:struct|interface)\b"),
        ("type", r"^type\s+(\w+)\s+\w"),
        ("fn", r"^func\s+(?:\(\s*\w+\s+\*?[\w.\[\]]+\s*\)\s*)?(\w+)\s*[\[(]"),
        ("const", r"^(?:const|var)\s+(\w+)\b"),
    ],
    "java": [
        ("class", rf"^\s*{MOD}(?:class|interface|enum|record|@interface)\s+(\w+)"),
        ("fn", rf"^\s*{MOD}(?:<[^>]+>\s+)?[\w<>\[\],.?]+\s+(\w+)\s*\([^;{{]*\)\s*(?:throws [\w., ]+)?\s*\{{"),
    ],
    "kotlin": [
        ("class", rf"^\s*{MOD}(?:class|interface|object|enum class)\s+(\w+)"),
        ("fn", rf"^\s*{MOD}fun\s+(?:<[^>]+>\s*)?(?:[\w.<>?]+\.)?(\w+)\s*\("),
        ("const", rf"^\s*{MOD}(?:const\s+)?(?:val|var)\s+([A-Z][A-Z0-9_]+)\b"),
    ],
    "csharp": [
        ("class", rf"^\s*{MOD}(?:class|interface|struct|enum|record)\s+(\w+)"),
        ("fn", rf"^\s*{MOD}[\w<>\[\],.?]+\s+(\w+)\s*\([^;{{]*\)\s*\{{?\s*$"),
    ],
    "rust": [
        ("struct", rf"^\s*{MOD}(?:struct|union)\s+(\w+)"),
        ("enum", rf"^\s*{MOD}enum\s+(\w+)"),
        ("trait", rf"^\s*{MOD}trait\s+(\w+)"),
        ("fn", rf"^\s*{MOD}(?:const\s+)?(?:async\s+)?fn\s+(\w+)"),
        ("type", rf"^\s*{MOD}type\s+(\w+)"),
        ("const", rf"^\s*{MOD}(?:const|static)\s+(\w+)\s*:"),
        ("mod", rf"^\s*{MOD}mod\s+(\w+)"),
    ],
    "ruby": [
        ("class", r"^\s*(?:class|module)\s+([\w:]+)"),
        ("fn", r"^\s*def\s+(?:self\.)?(\w+[?!=]?)"),
        ("const", r"^\s*([A-Z][A-Z0-9_]+)\s*="),
    ],
    "swift": [
        ("class", rf"^\s*{MOD}(?:class|struct|enum|protocol|extension|actor)\s+(\w+)"),
        ("fn", rf"^\s*{MOD}func\s+(\w+)"),
    ],
}
KEYWORDS = {"if", "for", "while", "switch", "catch", "return", "else", "new", "throw", "await", "elif", "foreach", "when"}


def clip(text: str, size: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= size else text[: size - 1] + "…"


def py_symbols(source: str) -> list[tuple]:
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    found = []

    def sig(node) -> str:
        try:
            args = ast.unparse(node.args)
        except Exception:
            args = "..."
        ret = f" -> {ast.unparse(node.returns)}" if getattr(node, "returns", None) else ""
        return f"({args}){ret}"

    def doc(node) -> str:
        text = ast.get_docstring(node) or ""
        return text.strip().splitlines()[0] if text.strip() else ""

    def walk(body, prefix=""):
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                kind = "method" if prefix else "fn"
                found.append((prefix + node.name, kind, node.lineno, sig(node), doc(node)))
            elif isinstance(node, ast.ClassDef):
                bases = ", ".join(ast.unparse(b) for b in node.bases)
                found.append((prefix + node.name, "class", node.lineno, f"({bases})" if bases else "", doc(node)))
                walk(node.body, prefix + node.name + ".")
            elif not prefix and isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                for target in targets:
                    if isinstance(target, ast.Name):
                        kind = "const" if target.id.isupper() else "var"
                        found.append((target.id, kind, node.lineno, "", ""))

    walk(tree.body)
    return found


def leading_doc(lines: list[str], index: int) -> str:
    """First text line of the comment block directly above lines[index], or ''."""
    if index == 0:
        return ""
    prev = lines[index - 1].strip()
    if prev.endswith("*/"):
        top = index - 1
        while top >= 0 and "/*" not in lines[top]:
            top -= 1
        for raw in lines[max(top, 0):index]:
            text = re.sub(r"^\s*(?:/\*+|\*+/?)\s?", "", raw.strip())
            text = re.sub(r"\s*\*/\s*$", "", text).strip()
            if text and not text.startswith("@"):
                return text
        return ""
    match = re.match(r"^(?://+!?|#(?!\[)|--)\s?(.*)$", prev)
    return match.group(1).strip() if match else ""


def regex_symbols(language: str, source: str) -> list[tuple]:
    rules = [(kind, re.compile(rx)) for kind, rx in PATTERNS.get(language, [])]
    found, lines = [], source.splitlines()
    current_class, class_indent = "", -1
    for index, line in enumerate(lines):
        if not line.strip() or len(line) > 400:
            continue
        indent = len(line) - len(line.lstrip())
        if current_class and indent <= class_indent and line.strip() not in ("}", "};", "end") and not line.lstrip().startswith(("@", ")", "]", "//", "*")):
            current_class = ""
        for kind, rx in rules:
            match = rx.match(line)
            if not match:
                continue
            name = match.group(1)
            if name in KEYWORDS:
                continue
            if kind == "member" and not (current_class and indent > class_indent):
                continue
            shown, label = name, ("fn" if kind == "member" else kind)
            if kind == "class":
                current_class, class_indent = name, indent
            elif kind in ("fn", "member") and current_class and indent > class_indent:
                shown, label = f"{current_class}.{name}", "method"
            signature = ""
            tail = line[match.end():]
            paren = re.match(r"\s*(\([^)]*\)?)", tail) if kind in ("fn", "member") else None
            if paren:
                signature = paren.group(1)
            doc = leading_doc(lines, index)
            found.append((shown, label, index + 1, signature, doc))
            break
    return found


def parse(path: Path, data: bytes) -> list[tuple]:
    language = LANG[path.suffix.lower()]
    source = data.decode("utf-8", errors="replace")
    return py_symbols(source) if language == "python" else regex_symbols(language, source)


def list_files(scope: str | None) -> list[str]:
    files: list[str] = []
    try:
        proc = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z", "-co", "--exclude-standard"],
                              capture_output=True, check=True)
        files = [f.decode("utf-8", "surrogateescape") for f in proc.stdout.split(b"\0") if f]
    except (OSError, subprocess.CalledProcessError):
        for base, dirs, names in os.walk(ROOT):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")]
            files += [str((Path(base) / n).relative_to(ROOT)) for n in names]
    keep = []
    for name in files:
        parts = Path(name).parts
        if any(part in SKIP_DIRS for part in parts[:-1]) or Path(name).suffix.lower() not in LANG:
            continue
        if ".min." in name or name.endswith((".d.ts", ".generated.ts")):
            continue
        if scope and not (name == scope or name.startswith(scope.rstrip("/") + "/")):
            continue
        if (ROOT / name).is_file():
            keep.append(name)
    return sorted(set(keep))


def group_key(path: str, depth: int) -> str:
    parts = Path(path).parts[:-1]
    if not parts:
        return "_root"
    width = max(depth, 2 if parts[0] in WIDE_ROOTS else 1)
    return "-".join(parts[:width])


def sym_line(path: str, sym: tuple) -> str:
    name, kind, line, signature, doc = sym
    path = path.replace("\n", "\\n").replace("\r", "\\r").replace("|", "\\|")
    row = f"{name} | {kind} | {path}:{line}"
    if signature:
        row += f" | {clip(signature, 110)}"
    if doc:
        row += f" | {clip(doc, 90)}" if signature else f" | | {clip(doc, 90)}"
    return row


def write_if_changed(path: Path, content: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def graphify_usable() -> bool:
    return bool(shutil.which("graphify")) and (ROOT / "graphify-out" / "graph.json").is_file()


def main() -> int:
    args = sys.argv[1:]
    if "--graphify" in args:
        usable = graphify_usable()
        print("graphify: usable" if usable else "graphify: not available")
        return 0
    scope = next((a.split("=", 1)[1] for a in args if a.startswith("--scope=")), None)
    if graphify_usable() and "--force" not in args:
        print("graphify is installed and has a graph: skipping the symbol index (use --force to build anyway)")
        return 0
    cache = {}
    if CACHE.is_file():
        try:
            cache = json.loads(CACHE.read_text(encoding="utf-8"))
        except ValueError:
            cache = {}
    entries = cache.get("files", {})
    files = list_files(scope)
    live = set(files)
    parsed, cache_dirty, render_dirty = 0, False, False
    for name in files:
        path = ROOT / name
        stat = path.stat()
        if stat.st_size > MAX_BYTES:
            if entries.pop(name, None) is not None:
                cache_dirty = render_dirty = True
            continue
        known = entries.get(name)
        if known and known.get("mtime") == stat.st_mtime_ns and known.get("size") == stat.st_size:
            continue  # same size and mtime: not re-read
        data = path.read_bytes()
        digest = hashlib.sha1(data).hexdigest()
        cache_dirty = True
        if known and known.get("hash") == digest:
            known["mtime"], known["size"] = stat.st_mtime_ns, stat.st_size
            continue
        entries[name] = {"hash": digest, "mtime": stat.st_mtime_ns, "size": stat.st_size,
                         "symbols": [list(sym) for sym in parse(path, data)]}
        parsed += 1
        render_dirty = True
    for name in list(entries):
        gone = not (ROOT / name).is_file() or Path(name).suffix.lower() not in LANG
        if (not scope and name not in live) or gone:
            del entries[name]
            cache_dirty = render_dirty = True
    if not render_dirty and (OUT / "INDEX.md").is_file() and all((OUT / o).is_file() for o in cache.get("outputs", [])):
        if cache_dirty:
            write_if_changed(CACHE, json.dumps({"files": entries, "outputs": cache.get("outputs", [])}, separators=(",", ":"), sort_keys=True))
        print("parsed 0 changed file(s); index is current")
        return 0

    # group symbols, splitting any group that renders to more than MAX_LINES_PER_FILE lines
    by_file = {n: [tuple(s) for s in e["symbols"]] for n, e in entries.items() if e["symbols"]}
    groups: dict[str, list[str]] = {}
    for name in by_file:
        groups.setdefault(group_key(name, 1), []).append(name)
    for _ in range(4):
        deeper = False
        for key, names in list(groups.items()):
            total = sum(len(by_file[n]) for n in names)
            depth = len(key.split("-")) + 1
            if total > MAX_LINES_PER_FILE and any(len(Path(n).parts) - 1 >= depth for n in names):
                del groups[key]
                for n in names:
                    groups.setdefault(group_key(n, depth), []).append(n)
                deeper = True
        if not deeper:
            break

    # depth exhausted but still too big (wide, shallow repos): split into numbered parts by whole files
    for key, names in list(groups.items()):
        if sum(len(by_file[n]) for n in names) <= MAX_LINES_PER_FILE:
            continue
        del groups[key]
        part, size, bucket = 1, 0, []
        for n in sorted(names):
            if bucket and size + len(by_file[n]) > MAX_LINES_PER_FILE:
                groups[f"{key}.p{part}"] = bucket
                part, size, bucket = part + 1, 0, []
            bucket.append(n)
            size += len(by_file[n])
        groups[f"{key}.p{part}"] = bucket

    OUT.mkdir(parents=True, exist_ok=True)
    changed, rows, written = [], [], set()
    for key in sorted(groups):
        names = sorted(groups[key])
        lines = [GENERATED, f"# Symbols: {key.replace('-', '/')}/", "",
                 "Up: [[code-analysis/INDEX|code-analysis]]", "", "`name | kind | path:line | signature | doc`", ""]
        count = 0
        for name in names:
            for sym in sorted(by_file[name], key=lambda s: s[2]):
                lines.append(sym_line(name, sym))
                count += 1
        fname = f"{key}.md"
        written.add(fname)
        if write_if_changed(OUT / fname, "\n".join(lines) + "\n"):
            changed.append(fname)
        rows.append((key, len(names), count, fname))

    written.add("INDEX.md")
    for old in cache.get("outputs", []):
        if old not in written and (OUT / old).is_file():
            (OUT / old).unlink()
            changed.append(old + " (removed)")

    languages = sorted({LANG[Path(n).suffix.lower()] for n in by_file})
    index = [GENERATED, "# Code analysis index", "",
             "Generated symbol index so agents can find code without reading whole files. "
             "Search with `grep -n -i \"<name>\" .agents/code-analysis/*.md`, then read only that range. "
             "Refresh with `python3 .agents/scripts/code-index.py` (see [[rules/13-code-analysis]]).", "",
             f"Files indexed: {len(by_file)} · Symbols: {sum(r[2] for r in rows)} · Languages: {', '.join(languages) or 'none'}"]
    best = [l for l in languages if l in BEST_EFFORT]
    if best:
        index.append(f"Best-effort (pattern based, may miss unusual syntax): {', '.join(best)}. Python is parsed exactly.")
    index += ["", "Kinds: fn, method, class, iface, type, enum, struct, trait, mod, const, var.", "", "## Groups", ""]
    index += [f"- [[code-analysis/{fname[:-3]}|{key.replace('-', '/')}/]]: {nfiles} files, {nsyms} symbols"
              for key, nfiles, nsyms, fname in rows]
    if write_if_changed(OUT / "INDEX.md", "\n".join(index) + "\n"):
        changed.append("INDEX.md")
    written.add("INDEX.md")

    cache = {"files": entries, "outputs": sorted(written)}
    write_if_changed(CACHE, json.dumps(cache, separators=(",", ":"), sort_keys=True))
    print(f"parsed {parsed} changed file(s), {len(by_file)} with symbols, {sum(r[2] for r in rows)} symbols; "
          f"{len(changed)} index file(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
