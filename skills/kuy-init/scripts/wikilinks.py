#!/usr/bin/env python3
"""Keep every Markdown document under .agents/ reachable by wikilink.

Every folder that holds documents gets a hub (an existing INDEX.md or README.md receives a
generated block; otherwise `00-<folder-slug>.md` is generated). Hubs link Up to their parent hub,
down to child hubs, and to every document. Top-level hubs are listed in a generated block of the
project's root AGENTS.md. Links are paths relative to .agents/ without the .md suffix.

Idempotent: a file is written only when its content changes, and changed paths are printed.

Usage:
  python3 .agents/scripts/wikilinks.py            regenerate hubs and the AGENTS.md block
  python3 .agents/scripts/wikilinks.py --check    write nothing; exit 1 if anything is out of date
"""
from __future__ import annotations

import pathlib
import re
import sys

AGENTS_DIR = pathlib.Path(__file__).resolve().parents[1]
ROOT_HUB = AGENTS_DIR.parent / "AGENTS.md"
GENERATED = "<!-- generated by .agents/scripts/wikilinks.py: do not edit by hand -->"
BLOCK_START = "<!-- wikilink-index:start -->"
BLOCK_END = "<!-- wikilink-index:end -->"
EXISTING_HUB_NAMES = ("INDEX.md", "README.md")
LINK = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")


def rel(path: pathlib.Path) -> str:
    return path.relative_to(AGENTS_DIR).as_posix()


def link_target(doc: pathlib.Path) -> str:
    return rel(doc)[: -len(".md")]


def title_of(doc: pathlib.Path) -> str:
    try:
        for line in doc.read_text(encoding="utf-8", errors="replace").splitlines()[:30]:
            if line.startswith("# "):
                return line[2:].strip().replace("|", "/").replace("]", ")").replace("[", "(")
    except OSError:
        pass
    return doc.stem


def link(doc: pathlib.Path) -> str:
    return f"[[{link_target(doc)}|{title_of(doc)}]]"


def all_docs() -> list[pathlib.Path]:
    docs = []
    for path in sorted(AGENTS_DIR.rglob("*.md")):
        parts = path.relative_to(AGENTS_DIR).parts
        if any(part.startswith(".") for part in parts):
            continue
        docs.append(path)
    return docs


def hub_for(folder: pathlib.Path) -> pathlib.Path:
    for name in EXISTING_HUB_NAMES:
        candidate = folder / name
        if candidate.is_file():
            return candidate
    slug = folder.name if folder != AGENTS_DIR else "agents"
    return folder / f"00-{slug}.md"


def is_generated(path: pathlib.Path) -> bool:
    return path.is_file() and path.read_text(encoding="utf-8", errors="replace").startswith(GENERATED)


def folders_with_docs(docs: list[pathlib.Path]) -> set[pathlib.Path]:
    folders: set[pathlib.Path] = set()
    for doc in docs:
        folder = doc.parent
        while folder != AGENTS_DIR.parent and AGENTS_DIR in (folder, *folder.parents):
            folders.add(folder)
            folder = folder.parent
    folders.discard(AGENTS_DIR)  # the root is AGENTS.md, handled separately
    return folders


def block_lines(folder: pathlib.Path, docs, folders, hubs, hub_text: str | None) -> list[str]:
    already = {m.strip() for m in LINK.findall(hub_text)} if hub_text else set()
    own = hubs[folder]
    lines = []
    parent = folder.parent
    if parent != AGENTS_DIR and parent in hubs:
        lines.append(f"Up: [[{link_target(hubs[parent])}|{parent.name}]]")
        lines.append("")
    children = sorted(c for c in folders if c.parent == folder)
    for child in children:
        target = link_target(hubs[child])
        if target not in already:
            lines.append(f"- [[{target}|{child.name}/]]")
    for doc in docs:
        if doc.parent != folder or doc == own:
            continue
        if any(doc == hubs[c] for c in children):
            continue
        if link_target(doc) not in already:
            lines.append(f"- {link(doc)}")
    return lines


def render_generated(folder, docs, folders, hubs) -> str:
    body = block_lines(folder, docs, folders, hubs, None)
    return "\n".join([GENERATED, f"# {rel(folder)}/", ""] + body) + "\n"


def read_raw(path: pathlib.Path) -> str:
    with open(path, encoding="utf-8", newline="") as handle:
        return handle.read()


def write_raw(path: pathlib.Path, content: str) -> None:
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(content)


def with_block(text: str, lines: list[str]) -> str:
    """Replace (or append) the generated block, keeping the file's own line endings."""
    if not lines and BLOCK_START not in text:
        return text
    eol = "\r\n" if "\r\n" in text else "\n"
    block = eol.join([BLOCK_START, GENERATED, ""] + lines + ["", BLOCK_END])
    start, end = text.find(BLOCK_START), text.find(BLOCK_END)
    if start != -1 and end > start:
        return text[:start] + block + text[end + len(BLOCK_END):]
    return text.rstrip("\r\n") + eol + eol + block + eol


def compute() -> dict[pathlib.Path, str]:
    """Return {path: new content} for every file that must exist with that content."""
    docs = [d for d in all_docs()]
    folders = folders_with_docs(docs)
    hubs = {folder: hub_for(folder) for folder in folders}
    # a generated hub is itself a doc; drop stale hubs of folders that no longer have real docs
    real = [d for d in docs if not is_generated(d)]
    folders = folders_with_docs(real) | {f for f in folders if any(d.parent == f for d in real)}
    hubs = {folder: hub_for(folder) for folder in folders}
    docs = sorted(set(real) | {h for h in hubs.values() if h.is_file() or is_generated(h)})
    out: dict[pathlib.Path, str] = {}
    for folder in sorted(folders):
        hub = hubs[folder]
        if hub.is_file() and not is_generated(hub):
            text = read_raw(hub)
            out[hub] = with_block(text, block_lines(folder, real + list(hubs.values()), folders, hubs, text))
        else:
            out[hub] = render_generated(folder, real + list(hubs.values()), folders, hubs)
    if ROOT_HUB.is_file():
        top = sorted(f for f in folders if f.parent == AGENTS_DIR)
        top_lines = [f"- [[{link_target(hubs[f])}|{f.name}/ ({sum(1 for d in real if f in d.parents)})]]" for f in top]
        loose = [d for d in real if d.parent == AGENTS_DIR]
        top_lines += [f"- {link(d)}" for d in loose]
        out[ROOT_HUB] = with_block(read_raw(ROOT_HUB), top_lines)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    if not AGENTS_DIR.is_dir():
        print("no .agents/ folder found", file=sys.stderr)
        return 2
    if not ROOT_HUB.is_file():
        print(f"warning: {ROOT_HUB.name} not found next to .agents/; top-level hubs are not registered", file=sys.stderr)
    changed = []
    for path, content in compute().items():
        current = read_raw(path) if path.is_file() else None
        if current == content:
            continue
        changed.append(path)
        if not check:
            write_raw(path, content)
    for path in changed:
        print(path.relative_to(AGENTS_DIR.parent).as_posix())
    if check and changed:
        print(f"{len(changed)} hub(s) out of date: run python3 .agents/scripts/wikilinks.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
